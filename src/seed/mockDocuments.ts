const NO_PAPER_FIELDS: string[] = [];

/**
 * 样稿封面的按类覆盖：周工作动态是按期下发的期刊，行首是期号、时间行排一周区间，
 * 与「应急报〔2026〕021号」那套发文字号不同（真件：「〔2026〕第13期」「4月11日-4月17日」）。
 * 只覆盖这两项，其余样稿字段仍由 category 推导。
 */
